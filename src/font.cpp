    const Glyph* find(char c) {
        c = (char)std::toupper((unsigned char)c);
        for (const Glyph& g : G) if (g.ch == c) return &g;
        return nullptr;                                    // spaces and unknown characters
    }
    void box(float x, float y, float w, float h, Color c, float a) {
        std::vector<Vec2> q = {{x, y}, {x + w, y}, {x + w, y + h}, {x, y + h}};
        if (a >= 0.999f) render::fillPolygon(q, c); else render::fillPolygonAlpha(q, c, a);
    }
    void run(const char* text, float x, float y, float px, Color c, float a) {
        for (const char* s = text; *s; s++, x += 6 * px) {
            const Glyph* g = find(*s);
            if (!g) continue;
            for (int r = 0; r < 7; r++)
                for (int col = 0; col < 5;) {              // merge neighbouring pixels into one rectangle
                    if (g->r[r][col] != '1') { col++; continue; }
                    int e = col;
                    while (e < 5 && g->r[r][e] == '1') e++;
                    box(x + col * px, y + r * px, (e - col) * px, px, c, a);
                    col = e;
                }
        }
    }
